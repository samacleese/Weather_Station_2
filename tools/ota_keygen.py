# ABOUTME: One-time ECDSA P-256 keypair generator for signing OTA firmware images.
# ABOUTME: Writes the private/public key PEMs and embeds the public key in a C++ header.
"""
Usage:
    python3 tools/ota_keygen.py --output-dir keys/ [--force]

Generates a P-256 keypair for signing OTA firmware manifests. Writes:
    keys/ecdsa_private.pem  — PKCS8 PEM, unencrypted. Keep offline; never commit.
    keys/ecdsa_public.pem   — SubjectPublicKeyInfo PEM.
    src/security/OTAPublicKey.h — the public key DER bytes as a const uint8_t[],
        embedded in firmware and used by mbedtls_ecdsa_verify() on the device.

Refuses to overwrite an existing private key unless --force is passed, since
overwriting it orphans any manifests already signed with the old key.
"""

import argparse
import subprocess
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

REPO_ROOT = Path(__file__).resolve().parent.parent
PUBLIC_KEY_HEADER = REPO_ROOT / "src" / "security" / "OTAPublicKey.h"


def format_header(der_bytes):
    array_body = ", ".join(f"0x{b:02x}" for b in der_bytes)
    return f"""// ABOUTME: ECDSA P-256 public key embedded in firmware for OTA signature verification.
// ABOUTME: Generated by tools/ota_keygen.py — do not edit by hand.
#ifndef OTA_PUBLIC_KEY_H
#define OTA_PUBLIC_KEY_H

#include <cstdint>

const uint8_t OTA_PUBLIC_KEY_DER[] = {{{array_body}}};

#endif  // OTA_PUBLIC_KEY_H
"""


def main():
    parser = argparse.ArgumentParser(description="Generate OTA signing keypair")
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--force", action="store_true", help="Overwrite an existing private key")
    args = parser.parse_args()

    private_key_path = args.output_dir / "ecdsa_private.pem"
    public_key_path = args.output_dir / "ecdsa_public.pem"

    if private_key_path.exists() and not args.force:
        print(f"ERROR: {private_key_path} already exists. Pass --force to overwrite.")
        sys.exit(1)

    args.output_dir.mkdir(parents=True, exist_ok=True)

    private_key = ec.generate_private_key(ec.SECP256R1())
    public_key = private_key.public_key()

    private_key_path.write_bytes(
        private_key.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
    )
    public_key_path.write_bytes(
        public_key.public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo,
        )
    )

    der_bytes = public_key.public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    PUBLIC_KEY_HEADER.write_text(format_header(der_bytes))
    subprocess.run(["clang-format", "-i", str(PUBLIC_KEY_HEADER)], check=True)

    print(f"Wrote {private_key_path} (keep offline, never commit)")
    print(f"Wrote {public_key_path}")
    print(f"Wrote {PUBLIC_KEY_HEADER}")


if __name__ == "__main__":
    main()
